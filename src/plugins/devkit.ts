/**
 * 15.2.0 plugin developer kit: `mcp-gateway plugin init` and `mcp-gateway plugin doctor`.
 *
 *  - {@link scaffoldPlugin} writes a plugin API v5 module that imports nothing but `node:` built-ins (so one signature
 *    covers it), a `plugins[]` config entry for it — `runtime: worker`, `failure: closed`, read-only arguments and
 *    responses, only the hooks it implements, no network, no environment, explicit limits — and a `node --test` file.
 *  - {@link doctorPlugins} loads every module plugin of a config file exactly the way the gateway does (signature
 *    check, runtime, options validation) and compares what the plugin implements with what its entry declares:
 *    runtime, plugin API version, hooks, network / environment permissions, limits, secrets and signature.
 *
 * Additive in 15.2: no gateway behaviour changes; the CLI only gains `plugin init` / `plugin doctor`.
 *
 * @module plugins/devkit
 */

import { resolve, isAbsolute } from 'node:path';
import { loadConfig } from '../config/loader.js';
import { loadPlugin, pluginRuntimeOf, runtimeOfConfig, PLUGIN_API_VERSION, PLUGIN_API_MIN_VERSION } from './index.js';
import type { PluginConfig } from '../utils/types.js';
import type { PluginPermissions, ModulePluginLimits } from './runtime.js';

/** Plugin names `plugin init` accepts: a letter or digit first, then letters, digits, `-` and `_` (max 64). */
export const PLUGIN_NAME_RE = /^[a-z0-9][a-z0-9_-]{0,63}$/;

/** Hooks a module plugin can implement (plugin API v5). */
export const PLUGIN_HOOKS = ['onToolCall', 'onResponse', 'onError', 'onConfigChange'] as const;

export interface ScaffoldOptions {
  /** Isolated runtime of the generated entry (default `worker`). */
  runtime?: 'worker' | 'process';
}

export interface Scaffold {
  name: string;
  /** File name → content (relative to the target directory). */
  files: Record<string, string>;
}

/** 15.2.0: the files of a new plugin (nothing is written here — the CLI writes them). */
export function scaffoldPlugin(name: string, opts: ScaffoldOptions = {}): Scaffold {
  if (!PLUGIN_NAME_RE.test(name)) throw new Error(`Plugin name "${name}" must match ${PLUGIN_NAME_RE} (lowercase letters, digits, - and _; no paths)`);
  const runtime = opts.runtime ?? 'worker';
  if (runtime !== 'worker' && runtime !== 'process') throw new Error('runtime must be worker or process');
  const mod = `// ${name} — a gateway plugin (plugin API v5), generated by \`mcp-gateway plugin init\`.
//
// It runs in an isolated ${runtime} runtime (see ${name}.config.yaml): it sees only the calls its permissions allow,
// cannot open network connections or read the gateway's environment, and a crash only ends its own runtime.
// Keep it self-contained (import node: built-ins only) so \`mcp-gateway plugin sign\` covers the whole plugin.

/** Validates plugins[].options when the plugin loads; an error refuses the plugin. */
export function checkOptions(options) {
  const errors = [];
  if (options.blockedTools !== undefined && !(Array.isArray(options.blockedTools) && options.blockedTools.every((t) => typeof t === 'string'))) {
    errors.push('blockedTools must be a list of tool names');
  }
  return errors;
}

/** The plugin for one set of options (exported for unit tests). */
export function create(options = {}) {
  const blocked = new Set(Array.isArray(options.blockedTools) ? options.blockedTools : []);
  return {
    name: '${name}',
    apiVersion: 5,
    configSchema: checkOptions,
    /**
     * Runs before every tool call this plugin may see (permissions.servers / tools).
     * Return { action: 'continue' } or { action: 'deny', reason } — argument rewrites need permissions.args: write.
     */
    onToolCall(call) {
      if (blocked.has(call.name)) return { action: 'deny', reason: \`\${call.name} is blocked by ${name}\` };
      return { action: 'continue' };
    },
  };
}

// The gateway calls the default export with { options, logger, gatewayVersion, apiVersion }.
export default (ctx) => create(ctx.options);
`;
  const config = `# plugins[] entry for ${name} — paste it into your gateway config (keep the paths relative to that file).
# Check it with: mcp-gateway plugin doctor -c <config file>
plugins:
  - module: ./${name}.mjs
    runtime: ${runtime}          # isolated runtime (15.0 default: worker)
    failure: closed            # a crash / timeout refuses the call
    options:
      blockedTools: []
    limits:
      timeoutMs: 500           # per hook call
      memoryMb: 64             # heap cap of the runtime
      maxConcurrent: 16        # hook calls in flight
    permissions:
      args: read               # argument rewrites are dropped (set "write" to allow them)
      response: read           # onResponse replacements are dropped
      hooks: [onToolCall]      # only the hooks the plugin implements
      network: false           # no outbound connections
      env: []                  # no environment variables
`;
  const test = `// node --test ${name}.test.mjs — unit tests for the plugin's hook logic (no gateway needed).
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { create, checkOptions } from './${name}.mjs';

const call = (name) => ({ serverId: 'demo', name, kind: 'tool', method: 'tools/call', arguments: {}, clientId: 'key:dev', via: 'rest', state: new Map() });

test('options are validated', () => {
  assert.deepEqual(checkOptions({ blockedTools: ['rm'] }), []);
  assert.equal(checkOptions({ blockedTools: 'rm' }).length, 1);
});

test('a blocked tool is denied, others continue', () => {
  const plugin = create({ blockedTools: ['rm'] });
  assert.equal(plugin.onToolCall(call('rm')).action, 'deny');
  assert.equal(plugin.onToolCall(call('ls')).action, 'continue');
});
`;
  return { name, files: { [`${name}.mjs`]: mod, [`${name}.config.yaml`]: config, [`${name}.test.mjs`]: test } };
}

export type CheckStatus = 'pass' | 'warn' | 'fail';
export interface DoctorCheck {
  id: string;
  status: CheckStatus;
  detail: string;
}
export interface PluginDoctorReport {
  /** `plugins[]` index. */
  index: number;
  module: string;
  name?: string;
  runtime: string;
  apiVersion?: number;
  hooks: string[];
  checks: DoctorCheck[];
}
export interface DoctorReport {
  ok: boolean;
  configFile: string;
  config: DoctorCheck;
  plugins: PluginDoctorReport[];
}

const msg = (e: unknown) => (e instanceof Error ? e.message : String(e));

/** 15.2.0: load and check every module plugin of a config file (see the module doc). */
export async function doctorPlugins(configFile: string): Promise<DoctorReport> {
  const file = resolve(configFile);
  let cfg;
  try {
    cfg = await loadConfig(file);
  } catch (e) {
    return { ok: false, configFile: file, config: { id: 'config', status: 'fail', detail: msg(e) }, plugins: [] };
  }
  const baseDir = cfg.configDir ?? process.cwd();
  const trust = cfg.pluginTrust as Parameters<typeof loadPlugin>[2];
  const entries = ((cfg.plugins ?? []) as PluginConfig[]).map((p, index) => ({ p, index })).filter(({ p }) => !!p.module);
  const plugins: PluginDoctorReport[] = [];
  for (const { p, index } of entries) plugins.push(await doctorOne(p, index, baseDir, trust));
  const ok = plugins.every((r) => r.checks.every((c) => c.status !== 'fail'));
  return { ok, configFile: file, config: { id: 'config', status: 'pass', detail: `valid (${entries.length} module plugin${entries.length === 1 ? '' : 's'})` }, plugins };
}

async function doctorOne(p: PluginConfig, index: number, baseDir: string, trust: Parameters<typeof loadPlugin>[2]): Promise<PluginDoctorReport> {
  const checks: DoctorCheck[] = [];
  const add = (id: string, status: CheckStatus, detail: string) => void checks.push({ id, status, detail });
  const spec = p.module!;
  const declared = runtimeOfConfig(p);
  const perms = (p.permissions ?? {}) as PluginPermissions;
  const limits = (p.limits ?? {}) as ModulePluginLimits;
  const report: PluginDoctorReport = { index, module: spec, runtime: declared, hooks: [], checks };
  add('config', 'pass', `plugins[${index}] is valid`);

  // load exactly as the gateway does: signature check, runtime, options validation
  let plugin: Awaited<ReturnType<typeof loadPlugin>> | undefined;
  let loadError: string | undefined;
  try {
    plugin = await loadPlugin(p, baseDir, trust);
  } catch (e) {
    loadError = msg(e);
  }
  const sigProblem = loadError && /signature|not signed|requireSigned|signed plugins/i.test(loadError);
  if (plugin) add('load', 'pass', `loaded in the ${pluginRuntimeOf(plugin)} runtime`);
  else add('load', 'fail', loadError ?? 'did not load');

  try {
    // runtime
    if (declared === 'inline') add('runtime', 'warn', 'runtime: inline runs the plugin in the gateway process (shared heap, no permissions.network / env / fs) — use worker or process unless it needs HTTP hooks');
    else add('runtime', 'pass', `runtime: ${declared}`);

    // plugin API version and hooks (only knowable once loaded)
    if (plugin) {
      report.name = plugin.name;
      report.apiVersion = plugin.apiVersion;
      const impl = PLUGIN_HOOKS.filter((h) => typeof (plugin as unknown as Record<string, unknown>)[h] === 'function');
      report.hooks = impl;
      const v = plugin.apiVersion;
      if (v === undefined) add('api', 'warn', `no apiVersion — declare apiVersion: ${PLUGIN_API_VERSION}`);
      else if (v < PLUGIN_API_MIN_VERSION || v > PLUGIN_API_VERSION) add('api', 'fail', `apiVersion ${v} is outside ${PLUGIN_API_MIN_VERSION}–${PLUGIN_API_VERSION}`);
      else add('api', 'pass', `plugin API v${v}`);
      if (!impl.length) add('hooks', 'warn', 'the plugin implements no hook (onToolCall / onResponse / onError / onConfigChange)');
      else if (!perms.hooks) add('hooks', 'warn', `permissions.hooks is not declared — every hook the plugin implements runs (${impl.join(', ')}); declare them to keep later versions from adding hooks silently`);
      else {
        const missing = perms.hooks.filter((h) => !impl.includes(h as (typeof PLUGIN_HOOKS)[number]));
        const undeclared = impl.filter((h) => !perms.hooks!.includes(h));
        const parts = [
          ...(missing.length ? [`declared but not implemented: ${missing.join(', ')}`] : []),
          ...(undeclared.length ? [`implemented but not in permissions.hooks (never runs): ${undeclared.join(', ')}`] : []),
        ];
        add('hooks', parts.length ? 'warn' : 'pass', parts.length ? parts.join('; ') : `permissions.hooks matches the plugin (${impl.join(', ')})`);
      }
    } else {
      add('api', 'warn', 'not checked (the plugin did not load)');
      add('hooks', 'warn', 'not checked (the plugin did not load)');
    }

    // permissions that only an isolated runtime enforces
    if (declared === 'inline') add('network', 'warn', 'an inline plugin can open any connection (permissions.network needs an isolated runtime)');
    else if (perms.network === undefined) add('network', 'warn', 'permissions.network is not declared — outbound connections are unrestricted; set false or list the hosts');
    else if (perms.network !== false && perms.network.includes('*')) add('network', 'warn', "permissions.network: ['*'] allows every connection");
    else add('network', 'pass', perms.network === false ? 'no outbound connections' : `only ${perms.network.join(', ')}`);
    if (perms.args === 'write' || perms.args === undefined) checks.push({ id: 'args', status: 'pass', detail: perms.args === undefined ? 'argument rewrites allowed (default write) — set permissions.args: read if the plugin only inspects calls' : 'argument rewrites allowed' });

    // limits
    const timeout = limits.timeoutMs ?? p.timeoutMs;
    if (declared === 'inline') add('limits', timeout ? 'pass' : 'warn', timeout ? `timeoutMs ${timeout}` : 'no timeoutMs — an inline hook call is not time limited');
    else if (limits.timeoutMs === undefined || limits.memoryMb === undefined) add('limits', 'warn', `limits.${limits.timeoutMs === undefined ? 'timeoutMs (default 5000)' : 'memoryMb (default 128)'} not set — declare the limits the plugin is tested with`);
    else add('limits', 'pass', `timeoutMs ${limits.timeoutMs}, memoryMb ${limits.memoryMb}, maxConcurrent ${limits.maxConcurrent ?? 16}`);

    // secrets
    const granted = Object.keys((p.secrets ?? {}) as Record<string, unknown>);
    const unknownSecrets = (perms.secrets ?? []).filter((s) => !granted.includes(s));
    if (unknownSecrets.length) add('secrets', 'fail', `permissions.secrets names secrets not granted in plugins[${index}].secrets: ${unknownSecrets.join(', ')}`);
    else if (granted.length) add('secrets', 'pass', `${granted.length} secret${granted.length === 1 ? '' : 's'} granted${perms.secrets ? `, ${perms.secrets.length} allowed` : ''}`);

    // signature
    const t = (trust ?? {}) as { requireSigned?: boolean; keys?: unknown[] };
    const isPath = spec.startsWith('.') || isAbsolute(spec);
    if (sigProblem) add('signature', 'fail', loadError!);
    else if (t.requireSigned || t.keys?.length) add('signature', plugin ? 'pass' : 'warn', plugin ? 'signature verified (pluginTrust)' : 'not checked (the plugin did not load)');
    else add('signature', 'warn', isPath ? 'unsigned and pluginTrust.requireSigned is off — sign it (mcp-gateway plugin sign) and require signatures in production' : 'package-name module: pluginTrust.requireSigned would refuse it');
  } finally {
    await plugin?.close?.();
  }
  return report;
}

/** Human-readable doctor report (one line per check). */
export function formatDoctor(r: DoctorReport): string {
  const icon = (s: CheckStatus) => (s === 'pass' ? '✓' : s === 'warn' ? '!' : '✗');
  const out = [`${icon(r.config.status)} config ${r.configFile}: ${r.config.detail}`];
  if (r.config.status === 'pass' && !r.plugins.length) out.push('  no module plugins configured');
  for (const p of r.plugins) {
    out.push('', `plugins[${p.index}] ${p.name ?? p.module} (${p.module}, runtime ${p.runtime}${p.hooks.length ? `, hooks ${p.hooks.join(', ')}` : ''})`);
    for (const c of p.checks) out.push(`  ${icon(c.status)} ${c.id}: ${c.detail}`);
  }
  out.push('', r.ok ? 'doctor: no failures' : 'doctor: FAILED');
  return out.join('\n');
}
